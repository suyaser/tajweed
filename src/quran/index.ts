const cache = new Map<number, Promise<Verse[]>>()

/** Fetches public/data/surah/NNN.json relative to the document base. Memoised; a failed load is retried next call. */
export function loadSurah(n: number): Promise<Verse[]> {
  let p = cache.get(n)
  if (!p) {
    const url = new URL(`data/surah/${String(n).padStart(3, '0')}.json`, document.baseURI)
    p = fetch(url).then((r) => {
      if (!r.ok) throw new Error(`surah ${n}: HTTP ${r.status}`)
      return r.json() as Promise<Verse[]>
    })
    p.catch(() => cache.delete(n))
    cache.set(n, p)
  }
  return p
}

const parse = (key: VerseKey) => key.split(':').map(Number) as [number, number]

export async function getVerse(key: VerseKey): Promise<Verse | undefined> {
  const [s, a] = parse(key)
  return (await loadSurah(s))[a - 1]
}

/** Verses from..to inclusive, across surah boundaries. */
export async function getRange(from: VerseKey, to: VerseKey): Promise<Verse[]> {
  const [s1, a1] = parse(from)
  const [s2, a2] = parse(to)
  const all = await Promise.all(Array.from({ length: s2 - s1 + 1 }, (_, i) => loadSurah(s1 + i)))
  return all.flatMap((verses, i) => {
    const s = s1 + i
    return verses.slice(s === s1 ? a1 - 1 : 0, s === s2 ? a2 : undefined)
  })
}

