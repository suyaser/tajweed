/**
 * cpfair rule → palette key (design §3.2, Dār al-Maʿrifa scheme).
 * - ghunnah: every place a ghunnah is heard: ghunnah (نّ/مّ), ikhfa, ikhfa_shafawi, iqlab, idghaam_ghunnah,
 *   idghaam_shafawi — green, as in the colour-coded muṣḥaf the learner reads from.
 * - merge: the مثلين/متجانسين/متقاربين cases (legend "إدغام").
 * - silent: letters written but not pronounced: hamzat_wasl, lam_shamsiyyah, silent, and idghaam_no_ghunnah
 *   (the span is the ن/تنوين that disappears into ل/ر).
 * - madd2 / madd45 (muttasil + munfasil) / madd246 (ʿāriḍ + līn) / madd6; qalqalah.
 * Our own annotations (src 'ours') may use a ColourKey as the rule name directly.
 */
export const RULE_COLOUR: Record<string, ColourKey> = {
  ghunnah: 'ghunnah', ikhfa: 'ghunnah', ikhfa_shafawi: 'ghunnah', iqlab: 'ghunnah',
  idghaam_ghunnah: 'ghunnah', idghaam_shafawi: 'ghunnah', idghaam_mutajanisayn: 'merge', idghaam_mutaqaribayn: 'merge',
  idghaam_no_ghunnah: 'silent', lam_shamsiyyah: 'silent', hamzat_wasl: 'silent', silent: 'silent',
  madd_2: 'madd2', madd_muttasil: 'madd45', madd_munfasil: 'madd45', madd_246: 'madd246', madd_6: 'madd6',
  qalqalah: 'qalqalah',
}
const COLOURS = new Set<string>(['clear', 'ghunnah', 'silent', 'merge', 'madd2', 'madd45', 'madd246', 'madd6', 'qalqalah', 'heavy', 'light'])
export const ruleColour = (rule: string): ColourKey | undefined => RULE_COLOUR[rule] ?? (COLOURS.has(rule) ? (rule as ColourKey) : undefined)

export interface Segment { text: string; rule?: string; colour?: ColourKey }

/**
 * Splits verse.text into consecutive segments covering it exactly (offsets are code points).
 * Where spans overlap, the shortest covering span wins (ties: the later one, so 'ours' after 'cpfair' wins).
 */
export function tajweedSpans(verse: Pick<Verse, 'text' | 'tajweed'>): Segment[] {
  const cps = Array.from(verse.text)
  const cuts = new Set([0, cps.length])
  for (const s of verse.tajweed) { cuts.add(Math.max(0, Math.min(s.start, cps.length))); cuts.add(Math.max(0, Math.min(s.end, cps.length))) }
  const pts = [...cuts].sort((a, b) => a - b)
  const out: Segment[] = []
  for (let i = 0; i + 1 < pts.length; i++) {
    const [a, b] = [pts[i], pts[i + 1]]
    let best: Verse['tajweed'][number] | undefined
    for (const s of verse.tajweed) if (s.start <= a && s.end >= b && (!best || s.end - s.start <= best.end - best.start)) best = s
    const text = cps.slice(a, b).join('')
    const last = out[out.length - 1]
    if (last && last.rule === best?.rule) last.text += text
    else out.push(best ? { text, rule: best.rule, colour: ruleColour(best.rule) } : { text })
  }
  return out
}

/** tajweedSpans grouped per word (verse.words order); spans crossing a space are split at it. */
export function wordSegments(verse: Pick<Verse, 'text' | 'tajweed'>): Segment[][] {
  const words: Segment[][] = [[]]
  for (const seg of tajweedSpans(verse)) {
    seg.text.split(' ').forEach((part, i) => {
      if (i > 0) words.push([])
      if (part) words[words.length - 1].push({ ...seg, text: part })
    })
  }
  return words
}
