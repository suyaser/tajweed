#!/usr/bin/env node
// src/styles/app.css (@theme = light, the `@variant dark` block = dark) + tokens.css (--t-* muṣḥaf palette)
// → mobile/lib/ui/tokens.g.dart. One source for the colours (docs/19 §2.6); tokens.test.ts stays the contrast check.
// `--check`: exit 1 if the Dart file is out of date (tool/check.sh).
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { tmpdir } from 'node:os'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../../', import.meta.url))
const app = readFileSync(root + 'src/styles/app.css', 'utf8')
const tok = readFileSync(root + 'src/styles/tokens.css', 'utf8')
const out = root + 'mobile/lib/ui/tokens.g.dart'

const between = (s, start, end) => {
  const i = s.indexOf(start)
  if (i < 0) throw new Error(`gen_tokens: "${start}" not found`)
  return s.slice(i + start.length, s.indexOf(end, i + start.length))
}
const decls = (block, prefix) =>
  Object.fromEntries([...block.matchAll(new RegExp(`--${prefix}-([\\w-]+):\\s*([^;]+);`, 'g'))].map((m) => [m[1], m[2].trim()]))

const camel = (s) => s.replace(/-(\w)/g, (_, c) => c.toUpperCase())
function dartColor(v) {
  let m = v.match(/^#([0-9a-f]{6})$/i)
  if (m) return `Color(0xff${m[1].toLowerCase()})`
  m = v.match(/^rgb\((\d+) (\d+) (\d+) \/ ([\d.]+)\)$/)
  if (m) {
    const hex = [Math.round(+m[4] * 255), +m[1], +m[2], +m[3]].map((n) => n.toString(16).padStart(2, '0')).join('')
    return `Color(0x${hex})`
  }
  return null // var(), transparent, currentColor, initial: aliases, not roles
}
function dartShadow(v) {
  const m = v.match(/^(-?\d+)(?:px)? (-?\d+)(?:px)? (\d+)px(?: (-?\d+)px)? (rgb\([^)]+\))$/)
  if (!m) throw new Error(`gen_tokens: shadow "${v}"`)
  return `[BoxShadow(offset: Offset(${m[1]}, ${m[2]}), blurRadius: ${m[3]}, spreadRadius: ${m[4] ?? 0}, color: ${dartColor(m[5])})]`
}
const px = (v) => (v.endsWith('rem') ? parseFloat(v) * 16 : parseFloat(v))

const lightBlock = between(app, '@theme {', '\n}')
const darkBlock = between(app, '@variant dark {', '} }')
const roles = (block) => Object.fromEntries(Object.entries(decls(block, 'color')).flatMap(([k, v]) => (dartColor(v) ? [[k, dartColor(v)]] : [])))
const light = roles(lightBlock)
const dark = roles(darkBlock)
const tLight = decls(between(tok, ':root {', '}'), 't')
const tDark = decls(between(tok, ':root[data-theme="dark"] {', '}'), 't')
const shLight = decls(lightBlock, 'shadow')
const shDark = decls(darkBlock, 'shadow')

const colorNames = Object.keys(light)
for (const k of colorNames) if (!dark[k]) throw new Error(`gen_tokens: no dark value for --color-${k}`)
const tNames = Object.keys(tLight)
const shadowNames = Object.keys(shLight)

const fields = [
  ...colorNames.map((k) => [camel(k), 'Color', light[k], dark[k]]),
  ...tNames.map((k) => [camel('t-' + k), 'Color', dartColor(tLight[k]), dartColor(tDark[k])]),
  ...shadowNames.map((k) => [camel('shadow-' + k), 'List<BoxShadow>', dartShadow(shLight[k]), dartShadow(shDark[k])]),
]
const lerp = (t) => (t === 'Color' ? 'Color.lerp' : 'BoxShadow.lerpList')

const spacing = decls(lightBlock, 'spacing')
const radius = decls(lightBlock, 'radius')

const dart = `// GENERATED by mobile/tool/gen_tokens.mjs from src/styles/app.css and src/styles/tokens.css. Do not edit.
import 'package:flutter/material.dart';

/// The web's colour roles (docs/13 Tokens) and muṣḥaf palette (t*), light and dark.
class AppColors extends ThemeExtension<AppColors> {
  const AppColors({${fields.map(([n]) => `required this.${n}`).join(', ')}});
${fields.map(([n, t]) => `  final ${t} ${n};`).join('\n')}

  static const light = AppColors(${fields.map(([n, , l]) => `${n}: ${l}`).join(', ')});
  static const dark = AppColors(${fields.map(([n, , , d]) => `${n}: ${d}`).join(', ')});

  @override
  AppColors copyWith({${fields.map(([n, t]) => `${t}? ${n}`).join(', ')}}) =>
      AppColors(${fields.map(([n]) => `${n}: ${n} ?? this.${n}`).join(', ')});

  @override
  AppColors lerp(AppColors? other, double t) => other == null
      ? this
      : AppColors(${fields.map(([n, ty]) => `${n}: ${lerp(ty)}(${n}, other.${n}, t)!`).join(', ')});
}

/// Spacing (--spacing-*), in logical pixels.
abstract final class Space {
${Object.entries(spacing).map(([k, v]) => `  static const double ${camel(k.replace(/^space-/, ''))} = ${px(v)};`).join('\n')}
}

/// Radii (--radius-*).
abstract final class Radii {
${Object.entries(radius).map(([k, v]) => `  static const double ${camel(k)} = ${px(v)};`).join('\n')}
}
`

// formatted like the rest (dart format, 120 columns), so --check compares like with like
const formatted = () => {
  const f = mkdtempSync(tmpdir() + '/tokens-') + '/tokens.g.dart'
  writeFileSync(f, dart)
  execFileSync('dart', ['format', '-l', '120', f], { stdio: 'ignore' })
  return readFileSync(f, 'utf8')
}
const next = formatted()
if (process.argv.includes('--check')) {
  let cur = ''
  try { cur = readFileSync(out, 'utf8') } catch { /* missing */ }
  if (cur !== next) { console.error('tokens.g.dart is out of date: run node mobile/tool/gen_tokens.mjs'); process.exit(1) }
} else {
  writeFileSync(out, next)
  console.log(`wrote ${out}: ${colorNames.length} roles, ${tNames.length} muṣḥaf colours, ${shadowNames.length} shadows`)
}
